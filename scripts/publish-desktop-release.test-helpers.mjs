// Test-only harness for the desktop release publisher tests.
//
// The canonical manifest writer lives in the MOSA repository; the read-only
// snapshot in ../mosa-writer-snapshot (next to this repository) is the current
// source of truth and the only writer the tests exercise. Its CLI resolves the
// packaged build identity (web/app/build-identity.json) from the repository it
// sits in, and that file is frozen inside the snapshot, so the CLI form can
// never emit a manifest. The tests therefore drive the exact exported
// prepareDesktopReleaseManifest() through a small generated CLI wrapper and
// inject a fixture build identity plus a throwaway Ed25519 signing key that is
// generated here, written to a temp directory, and deleted when the test
// process exits. Nothing in this file modifies the snapshot copy, touches any
// real signing key, or reaches any remote host.

import { createHash, generateKeyPairSync } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

// The canonical writer the wrapper delegates to. Overridable for local runs.
export const CANONICAL_WRITER_PATH =
  process.env.MOSA_RELEASE_CANONICAL_WRITER ||
  new URL("../../mosa-writer-snapshot/scripts/prepare-desktop-release-manifest.mjs", import.meta.url).pathname;

// Stands in for the packaged app's build identity in tests. The wrapper
// overrides productVersion with the --version argument of each invocation.
const FIXTURE_BUILD_IDENTITY = {
  gitSha: "a".repeat(40),
  uiFingerprint: "b".repeat(64),
  runtimeFingerprint: "c".repeat(64),
  distribution: "preview",
};

function wrapperSource(writerUrl, signatureUrl) {
  return [
    `// Generated by scripts/publish-desktop-release.test-helpers.mjs. Drives the`,
    `// canonical writer's exported prepareDesktopReleaseManifest() with a fixture`,
    `// build identity so tests can pin arbitrary release versions.`,
    `import { readFile, writeFile } from "node:fs/promises";`,
    `import { resolve } from "node:path";`,
    `import { releaseManifestPrivateKeyFromEnvironment } from ${JSON.stringify(signatureUrl)};`,
    `import { prepareDesktopReleaseManifest } from ${JSON.stringify(writerUrl)};`,
    ``,
    `function parseArgs(argv) {`,
    `  const args = {};`,
    `  for (let index = 0; index < argv.length; index += 1) {`,
    `    const token = argv[index];`,
    `    if (!token.startsWith("--")) continue;`,
    `    args[token.slice(2)] = argv[index + 1];`,
    `    index += 1;`,
    `  }`,
    `  return args;`,
    `}`,
    ``,
    `const args = parseArgs(process.argv.slice(2));`,
    `if (!args.version || !args.output) {`,
    `  throw new Error("Usage: test-manifest-writer.mjs --version <version> --output <latest.json> [--previous <latest.json>] [--mac <zip>] [--mac-app-name <name>] [--mac-team-identifier <id>] [--windows <zip>] [--windows-payload-exe-name <name>] [--windows-signer-thumbprint <id>] [--published-at <iso>] [--notes-zh <text>] [--notes-en <text>]");`,
    `}`,
    `const previousManifest = args.previous ? JSON.parse(await readFile(resolve(args.previous), "utf8")) : null;`,
    `const identityTemplate = JSON.parse(await readFile(process.env.MOSA_TEST_BUILD_IDENTITY_FILE, "utf8"));`,
    `const manifest = await prepareDesktopReleaseManifest({`,
    `  version: args.version,`,
    `  macArtifactPath: args.mac || "",`,
    `  macAppName: args["mac-app-name"] || "MOSA.app",`,
    `  macTeamIdentifier: args["mac-team-identifier"] || "",`,
    `  windowsArtifactPath: args.windows || "",`,
    `  windowsPayloadExeName: args["windows-payload-exe-name"] || "MOSA.exe",`,
    `  windowsSignerThumbprint: args["windows-signer-thumbprint"] || "",`,
    `  buildIdentity: { ...identityTemplate, productVersion: args.version },`,
    `  signingPrivateKey: releaseManifestPrivateKeyFromEnvironment(process.env),`,
    `  previousManifest,`,
    `  publishedAt: args["published-at"] || new Date().toISOString(),`,
    `  notes: { zh: args["notes-zh"] || "", en: args["notes-en"] || "" },`,
    `});`,
    `await writeFile(resolve(args.output), JSON.stringify(manifest, null, 2) + "\\n", "utf8");`,
    ``,
  ].join("\n");
}

export async function createWriterHarness() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "mosa-release-writer-harness."));
  process.on("exit", () => fs.rmSync(dir, { recursive: true, force: true }));

  // Red line 2: this is a throwaway key generated for this test run only.
  const { privateKey, publicKey } = generateKeyPairSync("ed25519");
  const privateKeyPath = path.join(dir, "release-manifest-private-key.pem");
  fs.writeFileSync(privateKeyPath, privateKey.export({ format: "pem", type: "pkcs8" }), { mode: 0o600 });

  // Mirrors createReleaseManifestTrust(): key id = SHA-256 of the SPKI DER.
  const keyId = createHash("sha256")
    .update(publicKey.export({ format: "der", type: "spki" }))
    .digest("hex");
  const identityPath = path.join(dir, "build-identity.json");
  fs.writeFileSync(identityPath, `${JSON.stringify({
    ...FIXTURE_BUILD_IDENTITY,
    releaseManifestTrust: {
      algorithm: "ed25519",
      keyId,
      publicKeyPem: publicKey.export({ format: "pem", type: "spki" }).toString(),
    },
  }, null, 2)}\n`);

  const writerUrl = pathToFileURL(CANONICAL_WRITER_PATH).href;
  const signatureUrl = pathToFileURL(path.resolve(path.dirname(CANONICAL_WRITER_PATH), "../lib/release-manifest-signature.mjs")).href;
  const writerPath = path.join(dir, "test-manifest-writer.mjs");
  fs.writeFileSync(writerPath, wrapperSource(writerUrl, signatureUrl));

  // Exported so both the publish script runs (via safeEnv's process.env
  // spread) and direct writer invocations (which inherit process.env) sign
  // with the same throwaway key and fixture identity.
  process.env.MOSA_RELEASE_MANIFEST_PRIVATE_KEY_FILE = privateKeyPath;
  process.env.MOSA_TEST_BUILD_IDENTITY_FILE = identityPath;

  return {
    dir,
    writerPath,
    privateKeyPath,
    identityPath,
    buildIdentity: { ...FIXTURE_BUILD_IDENTITY },
  };
}
